"""Render docs/system_design.md from the system section of ml_spec.yaml and the reasoning in the answers.

The settings table and the diagram come from the spec only, so they always match it. The reasoning comes from the
answers file, which nb_common.cli keeps in answers/11_system.yaml, so a rebuild reproduces the document exactly.
"""

from __future__ import annotations

import datetime as _dt


TITLES = {
    "ingestion": "Data ingestion",
    "data_validation": "Data validation",
    "features": "Feature pipeline and feature store",
    "training": "Training pipeline",
    "registry": "Model registry and champion/challenger gate",
    "inference": "Inference",
    "serving": "Serving and deployment",
    "label_feedback": "Label feedback",
    "monitoring": "Monitoring",
    "failure_handling": "Failure handling and fallbacks",
    "orchestration": "Orchestration",
    "testing": "Testing strategy",
}
SHORT = {"ingestion": "Ingestion", "data_validation": "Validation", "features": "Features", "training": "Training",
         "registry": "Registry and gate", "inference": "Inference", "serving": "Serving",
         "label_feedback": "Label feedback", "monitoring": "Monitoring", "failure_handling": "Fallback",
         "orchestration": "Orchestration", "testing": "Tests"}
# Data flow between the components: (from, to, label). Dotted edges control rather than carry data.
EDGES = [("ingestion", "data_validation", "raw data"), ("data_validation", "features", "valid data"),
         ("features", "training", "training data"), ("training", "registry", "candidate model"),
         ("registry", "inference", "champion"), ("features", "inference", "serving features"),
         ("inference", "serving", "predictions"), ("inference", "label_feedback", "prediction log"),
         ("ingestion", "label_feedback", "actuals"), ("label_feedback", "monitoring", "scored predictions"),
         ("label_feedback", "registry", "live scores for the gate")]
CONTROL = [("monitoring", "training", "retrain trigger"), ("failure_handling", "serving", "fallback"),
           ("orchestration", "ingestion", "schedules"), ("orchestration", "training", ""),
           ("orchestration", "inference", "")]
PLATFORM = {"default": "the default stack", "neutral": "no tools yet (tool neutral)"}


def _v(x, empty="Not decided yet."):
    if x is None or x == "" or x == [] or x == {}:
        return empty
    return str(x)


def _label(text):
    return str(text).replace('"', "'").replace("\n", " ")


def _fmt(value):
    if isinstance(value, dict):
        return "; ".join(f"{k.replace('_', ' ')}: {_fmt(v)}" for k, v in value.items())
    if isinstance(value, list):
        return ", ".join(_fmt(v) for v in value) if value else "none"
    return _label(value).replace("|", "/")


def mermaid(comps):
    L = ["```mermaid", "flowchart LR"]
    for c in TITLES:
        e = comps.get(c) or {}
        if not e:
            text = f"{SHORT[c]}<br/>not decided"
        elif e.get("needed") is False:
            text = f"{SHORT[c]}<br/>not needed"
        else:
            text = f"{SHORT[c]}<br/>{_label(e.get('tool') or 'tool not chosen')}"
        L.append(f'    {c}["{text}"]')
    for a, b, lab in EDGES:
        L.append(f"    {a} -->|{lab}| {b}" if lab else f"    {a} --> {b}")
    for a, b, lab in CONTROL:
        L.append(f"    {a} -.->|{lab}| {b}" if lab else f"    {a} -.-> {b}")
    off = [c for c in TITLES if not comps.get(c) or (comps.get(c) or {}).get("needed") is False]
    if off:
        L.append("    classDef off stroke-dasharray: 5 5,color:#888")
        L.append(f"    class {','.join(off)} off")
    L.append("```")
    return L


def render(spec, reasoning=None):
    reasoning = reasoning or {}
    pr = spec.get("project") or {}
    s = spec.get("system") or {}
    comps = s.get("components") or {}
    plat = s.get("platform") or {}
    plat_text = str(plat.get("name") or "a platform").capitalize() if plat.get("kind") == "platform" else PLATFORM.get(plat.get("kind"), _v(plat.get("kind")))
    entry = s.get("entry") or {}
    needed = [c for c in TITLES if comps.get(c) and comps[c].get("needed") is not False]
    dropped = [c for c in TITLES if comps.get(c) and comps[c].get("needed") is False]
    dep = s.get("champion_dependent") or []
    L = [f"# System Design: {pr.get('name')}", "",
         f"**Status:** {_v(s.get('status'), 'draft').capitalize()}  ",
         f"**Last updated:** {_dt.date.today():%Y-%m-%d}  ",
         f"**Designed for champion:** {_v(s.get('champion'), 'unknown')}  ",
         "**Source:** written by ml-system-design from `ml_spec.yaml` (section `system`) and the answers in "
         "`answers/11_system.yaml`. Change the answers and rebuild; do not edit this file.", "",
         "## Summary", "",
         " ".join(x for x in [
             f"The system is built on {plat_text}.",
             f"It has {len(needed)} components" + (f"; {len(dropped)} are not needed ({', '.join(TITLES[c].lower() for c in dropped)})." if dropped else "."),
             f"The design started from this evaluation decision: {str(entry.get('evaluation_decision')).rstrip('.')}." if entry.get("evaluation_decision") else "",
             "It was designed with an override of the entry rule: " + str(entry.get("reason")).rstrip(".") + "." if entry.get("outcome") == "override" else "",
             "It is a design only; each component is built later." ,
         ] if x), ""]
    if reasoning.get("platform"):
        L += ["## Platform", "", str(reasoning["platform"]).strip(), ""]
    if reasoning.get("entry"):
        L += ["## Why the System Is Built Now", "", str(reasoning["entry"]).strip(), ""]
    L += ["## Diagram", "", "Solid arrows carry data; dotted arrows control or trigger. Dashed boxes are not needed "
          "or not decided.", ""] + mermaid(comps) + [""]
    L += ["## Settings", "", "| Component | Needed | Tool | Settings |", "|---|---|---|---|"]
    for c, title in TITLES.items():
        e = comps.get(c)
        if not e:
            L.append(f"| {title} | Not decided | | |")
            continue
        need = "No" if e.get("needed") is False else "Yes"
        L.append(f"| {title}{' (champion dependent)' if c in dep else ''} | {need} | {_fmt(e.get('tool') or '')} | "
                 f"{_fmt(e.get('settings') or {}) if e.get('settings') else ''} |")
    L += ["", "Parts marked champion dependent are redrafted when the champion changes; the rest is kept.", ""]
    L += ["## Components", ""]
    for c, title in TITLES.items():
        e = comps.get(c) or {}
        L += [f"### {title}", ""]
        if not e:
            L += ["Not decided yet.", ""]
            continue
        if e.get("needed") is False:
            L += [f"Not needed. {_v(e.get('reason'), '')}".strip(), ""]
            continue
        text = str(reasoning.get(c) or e.get("reason") or "").strip()
        L += [text or "No reasoning recorded.", ""]
    acc = [w for w in s.get("warnings_accepted") or [] if isinstance(w, dict)]
    L += ["## Warnings Accepted", ""]
    L += ([f"* **{w.get('check')}:** {w.get('reason')}" for w in acc] or ["None."]) + [""]
    L += ["## Risks", ""]
    L += ([f"* {r.get('problem')} {r.get('resolution') or ''}".rstrip() for r in s.get("risks") or []
           if isinstance(r, dict)] or ["None recorded."]) + [""]
    oq = [q for q in spec.get("open_questions") or [] if isinstance(q, dict) and q.get("status") == "open"
          and q.get("stage") == "system"]
    L += ["## Open Questions", ""]
    if oq:
        L += ["| ID | Question |", "|---|---|"] + [f"| {q.get('id')} | {q.get('question')} |" for q in oq]
    else:
        L += ["None."]
    ds = [d for d in spec.get("decisions") or [] if isinstance(d, dict) and d.get("stage") == "system"
          and not d.get("superseded_by")]
    L += ["", "## Decisions", ""]
    L += ([f"* {d.get('decision')} {d.get('reason') or ''}".rstrip() for d in ds] or ["None recorded."])
    return "\n".join(L).rstrip() + "\n"
